#!/usr/bin/env bash
# Called by sql/outbox-export-session.sql (via \!) once the export snapshot
# is open and /dump/export-facts.txt is written. Checks the facts the
# encoder depends on, then writes /dump/plan.sql: the parts requested in
# ROBIN_PARTS, in priority order, each chunk preceded by an egress budget
# check. Exits non-zero (and writes no plan) if anything is unexpected, so
# that no row is read.
set -Eeuo pipefail
DUMP=/dump
FACTS=$DUMP/export-facts.txt
PLAN=$DUMP/plan.sql
LOG=/out/export.log
log() { printf '%s %s\n' "$(date -u +%FT%TZ)" "$*" | tee -a "$LOG" >&2; }
fact() { awk -F'|' -v k="$1" '$1 == k { print substr($0, length(k) + 2); found = 1 } END { if (!found) exit 1 }' "$FACTS"; }
refuse() { log "PLAN REFUSED: $*"; printf 'FAIL|export_plan|%s\n' "$*" >> /out/checks.txt; exit 1; }

rm -f "$PLAN"
[[ -s $FACTS ]] || refuse "no facts were recorded"

# The compact encoding (sql/outbox-encode-rows.sql) knows these 13 columns
# and nothing else. Any other table shape stops the export here.
expected='sequence_id bigint not null, id uuid not null, aggregate_type text not null, aggregate_id uuid not null, event_type text not null, schema_version integer not null, payload jsonb not null, correlation_id uuid not null, causation_id uuid, created_at timestamp with time zone not null, published_at timestamp with time zone, attempt_count integer not null, last_error text'
cols=$(fact outbox_columns) || refuse "outbox_columns missing"
[[ $cols == "$expected" ]] || refuse "public.outbox_events has columns ($cols), expected ($expected)"
[[ $(fact outbox_generated_columns) == 0 ]] || refuse "public.outbox_events has generated columns"
[[ $(fact pgcrypto_schema) == extensions ]] || refuse "pgcrypto is not installed in schema extensions"
[[ $(fact transaction_read_only) == on ]] || refuse "the export transaction is not read-only"
[[ $(fact transaction_isolation) == 'repeatable read' ]] || refuse "the export transaction is not REPEATABLE READ"
vnum=$(fact server_version_num)
(( vnum / 10000 == 17 )) || refuse "expected PostgreSQL 17, got $vnum"

CHUNK=${ROBIN_CHUNK_ROWS:?}
[[ $CHUNK =~ ^[1-9][0-9]*$ ]] || refuse "ROBIN_CHUNK_ROWS is not a positive number"
pending_jd=$(fact pending_job_discovered)
reltuples=$(fact outbox_reltuples)
(( reltuples < 0 )) && reltuples=0
case ${ROBIN_PARTS:?} in
  pending)   parts=(D A1 S B1) ;;
  published) parts=(D B2) ;;
  all)       parts=(D A1 S B1 B2) ;;
  *) refuse "ROBIN_PARTS must be pending, published or all" ;;
esac
# First-chunk size estimates for the budget check (later chunks use the
# largest chunk already received). Generous on purpose: the production probe
# of 8 Nov measured 47-52 bytes per row after compression.
est_rows=$(( CHUNK * 80 + 65536 ))
est_dict=$(( $(fact jobs_rows) * 24 + 65536 ))
nil=00000000-0000-0000-0000-000000000000

{
  echo "-- generated by outbox-plan.sh at $(date -u +%FT%TZ): parts ${parts[*]}, $CHUNK rows per chunk"
  echo "\\set chunk_rows $CHUNK"
  echo "\\set lo 0"
  echo "\\set hi 0"
  echo "\\set lo_id $nil"
  echo "\\set hi_id $nil"
  for p in "${parts[@]}"; do
    case $p in
      D|S|A1)
        est=$est_dict; [[ $p == A1 ]] && est=1048576
        cat <<EOF
\\echo 'part $p'
\\! bash /work/outbox-budget.sh check $p 1 $est
\\if :SHELL_ERROR
\\echo 'egress budget reached: stopping before part $p'
\\quit
\\endif
\\set part $p
\\set chunk 1
\\set out $DUMP/chunks/$p-0001.bin
EOF
        if [[ $p == A1 ]]; then echo "\\i /work/outbox-encode-rows.sql"; else echo "\\i /work/outbox-encode-other.sql"; fi
        echo "\\! bash /work/outbox-budget.sh done $p 1"
        echo "\\! bash /work/outbox-budget.sh complete $p"
        ;;
      B1|B2)
        if [[ $p == B1 ]]; then
          steps=$(( (pending_jd + CHUNK - 1) / CHUNK + 1 ))
        else
          steps=$(( (reltuples * 12 / 10) / CHUNK + 3 ))
        fi
        echo "\\echo 'part $p: up to $steps chunks'"
        echo "\\set more true"
        for (( k = 1; k <= steps; k++ )); do
          c=$(printf '%04d' "$k")
          echo "\\if :more"
          if [[ $p == B1 ]]; then
            cat <<'EOF'
SELECT count(*) > 0 AS has_rows, coalesce(max(sequence_id), 0) AS hi
  FROM (SELECT sequence_id FROM public.outbox_events
         WHERE published_at IS NULL AND event_type = 'job.discovered' AND sequence_id > :lo
         ORDER BY sequence_id LIMIT :chunk_rows) s \gset
EOF
          else
            cat <<'EOF'
WITH nxt AS (SELECT id FROM public.outbox_events
              WHERE published_at IS NOT NULL AND id > :'lo_id'::uuid
              ORDER BY id LIMIT :chunk_rows)
SELECT count(*) > 0 AS has_rows, coalesce((SELECT id::text FROM nxt ORDER BY id DESC LIMIT 1), :'lo_id') AS hi_id
  FROM nxt \gset
EOF
          fi
          cat <<EOF
\\if :has_rows
\\! bash /work/outbox-budget.sh check $p $k $est_rows
\\if :SHELL_ERROR
\\echo 'egress budget reached: stopping before part $p chunk $k'
\\quit
\\endif
\\set part $p
\\set chunk $k
\\set out $DUMP/chunks/$p-$c.bin
\\i /work/outbox-encode-rows.sql
\\! bash /work/outbox-budget.sh done $p $k
EOF
          if [[ $p == B1 ]]; then echo "\\set lo :hi"; else echo "\\set lo_id :hi_id"; fi
          cat <<EOF
\\else
\\set more false
\\! bash /work/outbox-budget.sh complete $p
\\endif
\\endif
EOF
        done
        cat <<EOF
\\if :more
\\echo 'part $p needs more than $steps chunks: stopping'
\\! bash /work/outbox-budget.sh overflow $p
\\quit
\\endif
EOF
        ;;
    esac
  done
} > "$PLAN"
log "plan written: parts ${parts[*]}; $CHUNK rows per chunk; pending job.discovered $pending_jd; reltuples $reltuples"
